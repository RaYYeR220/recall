/**
 * Copies the `abi` arrays from the Foundry artifacts into packages/sdk/src/abi.ts
 * as `as const` tuples, so viem infers exact types.
 *
 * Usage:  forge build && bun run scripts/gen-abi.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");

const targets = [
  { name: "debitRailAbi", artifact: "contracts/out/DebitRail.sol/DebitRail.json" },
  { name: "railLensAbi", artifact: "contracts/out/RailLens.sol/RailLens.json" },
] as const;

let out = `// GENERATED by scripts/gen-abi.ts from contracts/out. Do not edit by hand.\n`;
out += `// Regenerate with: forge build && bun run scripts/gen-abi.ts\n\n`;

for (const t of targets) {
  const path = join(root, t.artifact);
  const json = JSON.parse(readFileSync(path, "utf8")) as { abi?: unknown[] };
  if (!Array.isArray(json.abi)) throw new Error(`No abi array in ${t.artifact}. Run forge build first.`);
  out += `export const ${t.name} = ${JSON.stringify(json.abi, null, 2)} as const;\n\n`;
  console.log(`${t.name}: ${json.abi.length} entries from ${t.artifact}`);
}

const dest = join(root, "packages/sdk/src/abi.ts");
writeFileSync(dest, out.trimEnd() + "\n");
console.log(`wrote ${dest}`);
